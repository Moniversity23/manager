// Builds the offline browser engine: src/webEngine.js (+ the whole engine and data pack) →
// public/engine.worker.js, and vendors three.js for the 3D match view into public/vendor/.
// Runs automatically before `npm start` and `npm test`.
const path = require('path');
const fs = require('fs');
let esbuild;
try { esbuild = require('esbuild'); } catch {
  // Production installs (npm ci --omit=dev) have no esbuild: use the engine that was built earlier.
  if (fs.existsSync(path.join(__dirname, '..', 'public', 'engine.worker.js'))) { console.log('esbuild not installed: using the existing public/engine.worker.js'); process.exit(0); }
  console.error('esbuild is missing and public/engine.worker.js has not been built. Run: npm install && npm run build'); process.exit(1);
}

const root = path.join(__dirname, '..');
const out = path.join(root, 'public', 'engine.worker.js');

esbuild.buildSync({
  entryPoints: [path.join(root, 'src', 'webEngine.js')],
  bundle: true, format: 'iife', platform: 'browser', target: ['es2020'], minify: !process.env.GAFFER_DEBUG_BUILD,
  outfile: out, legalComments: 'none', logLevel: 'warning',
  banner: { js: '// The Gaffer offline engine — generated by scripts/build-web.js, do not edit.' },
});
console.log(`engine.worker.js: ${(fs.statSync(out).size / 1024).toFixed(0)} KB`);

const three = path.join(root, 'node_modules', 'three', 'build', 'three.module.min.js');
const vendor = path.join(root, 'public', 'vendor', 'three.module.min.js');
if (fs.existsSync(three)) {
  fs.mkdirSync(path.dirname(vendor), { recursive: true });
  fs.copyFileSync(three, vendor);
  console.log(`vendor/three.module.min.js: ${(fs.statSync(vendor).size / 1024).toFixed(0)} KB`);
} else if (!fs.existsSync(vendor)) console.warn('three.js not installed: the 3D match view falls back to 2D');

// The glTF loader and skeleton tools for the motion-captured players (three.js add-ons). Their
// "from 'three'" imports are pointed at the vendored build so no import map is needed.
const jsm = path.join(root, 'node_modules', 'three', 'examples', 'jsm');
for (const rel of ['loaders/GLTFLoader.js', 'utils/SkeletonUtils.js', 'utils/BufferGeometryUtils.js']) {
  const src = path.join(jsm, rel), dst = path.join(root, 'public', 'vendor', 'jsm', rel);
  if (!fs.existsSync(src)) { if (!fs.existsSync(dst)) console.warn(`three.js add-on missing: ${rel} (the 3D view uses classic figures)`); continue; }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, fs.readFileSync(src, 'utf8').replace(/from 'three';/g, "from '../../three.module.min.js';"));
}
console.log('vendor/jsm: GLTFLoader, SkeletonUtils, BufferGeometryUtils');
